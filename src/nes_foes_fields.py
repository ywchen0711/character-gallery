def field_pals(rows, cols):
    """(layer 1 slots, layer 2 slots) for a frame: slot -> NES colour; each layer at most 3 colours + transparent."""
    cols = dict(cols)
    cols['k'] = 0x0F
    cnt = {}
    for r in rows:
        for ch in r:
            if ch != '.':
                cnt[cols[ch]] = cnt.get(cols[ch], 0) + 1
    others = sorted((v for v in cnt if v != 0x0F), key=lambda v: (-cnt[v], v))
    l1, l2 = [0x0F] + others[:2], others[2:]
    if len(l2) > 3:
        raise ValueError('field sprite needs %d colours (max 6 over two layers)' % len(cnt))
    used = {ch for r in rows for ch in r if ch != '.'}
    return ({ch: cols[ch] for ch in sorted(used) if cols[ch] in l1},
            {ch: cols[ch] for ch in sorted(used) if cols[ch] in l2})
