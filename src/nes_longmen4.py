"""龍門武林, fourth group: the new people of 龍門刀客傳 貳 · 萬妖鈴 (Longmen Quest II) in the 8-bit `nes` style.

Field sprites (16x24) are hand-typed like the rest of the cast: 'k' black, 'S' skin, 'c' the main colour on the first
sprite layer, and up to three more colours on a second stacked layer (`pal2`): hats, props, trims. Each has a front
view, a side view (stride) and the side legs-together rows (`side2`), and a back view (`back`), which Longmen Quest II
uses for the party's cards in battle. Walk frame 2 keeps the body and only moves the bottom rows (nes_walk.py).
The 48x56 portraits are drawn in the 霸王之路 bust style by nes_longmen4_busts.py (mondraw shapes, hand-stamped
heads), split into the background layer and sprite overlay by mondraw.famicom().
nes_longmen.py merges PORTRAITS, SPRITES and HEIGHTS from here.
"""


def _G(t):
    rows = [ln.strip() for ln in t.strip('\n').split('\n')]
    assert len(rows) == 24 and all(len(r) == 16 for r in rows), [(i, len(r), r) for i, r in enumerate(rows) if len(r) != 16] or len(rows)
    return rows


def _L(t):
    return [ln.strip() for ln in t.strip('\n').split('\n')]


