def person(head, body, item='none', pal=None, pal2=None, extra=None, extra_side=None, sub=None):
    hf, hs = HEADS[head]
    bf, bs, b2 = BODIES[body]
    itf, its = ITEMS[item]
    front = _over(hf + bf, itf)
    side = _over(hs + bs, its)
    if extra:
        front = _over(front, _R(extra, 24))
    if extra_side:
        side = _over(side, _R(extra_side, 24))
    if sub:
        front, side, b2 = _sub(front, sub), _sub(side, sub), _sub(b2, sub)
    d = dict(pal=pal, front=front, side=side, side2=b2)
    if pal2:
        d['pal2'] = pal2
    return d


