"""龍門江湖志 (Sects of Longmen): the troops, crews, great people and the abbess of the Mercy Cloud Nunnery.

16x24 field sprites in the `nes` style, built from hand-typed parts so a whole army reads as one family:
a head (front 12 rows + side 12 rows), a body (front + side 12 rows, plus the side legs-together rows) and a
held weapon or prop laid over them. Letters: 'k' black, 'S' skin, 'c' the main cloth (first sprite layer);
three more letters per figure on the stacked second layer (`pal2`): hats, trims, blades, wood.
Mounts and vehicles (riders, carts, siege engines, boats) are drawn whole.
The 48x56 portraits are 霸王之路-style busts (nes_sects_busts.py); for carts, engines and ships the bust is the
unit's crew (the escort master, the engineer, the boatman ...).
nes_longmen.py merges PORTRAITS, SPRITES and HEIGHTS from here.
"""


def _R(t, n):
    rows = [ln.strip() for ln in t.strip('\n').split('\n')]
    assert len(rows) == n and all(len(r) == 16 for r in rows), [(i, len(r), r) for i, r in enumerate(rows) if len(r) != 16] or (len(rows), n)
    return rows


def _over(base, top):
    out = []
    for a, b in zip(base, top):
        out.append(''.join(y if y != '.' else x for x, y in zip(a, b)))
    return out


def _sub(rows, mapping):
    return [''.join(mapping.get(ch, ch) for ch in r) for r in rows]


