"""三國志 霸王之路 (Path of the Hegemon): Jeff as the main general and the enemy general of every stage.

Same `nes` rules as nes_portraits.py: 48x56 portraits on black, NES 2C02 colours, one 3-colour sub-palette per
16x16 area (max 4), sprite overlays (eye whites, blades, feathers, tassels).
16x24 field sprites use two NES sprite layers, the way Famicom games stacked a second sprite over a figure: `pal`
(k black, S skin, c the general's main colour) for the body and `pal2` (three more colours) for the overlay -
helmet, plume or feathers, beard, cape, trim and the weapon in hand - so each sprite carries the portrait's headgear,
beard, armour colours and signature weapon. One letter = one colour of one layer; nes.sprite_image() checks that each
layer stays within 3 colours + transparent. `legs['front']` is front walk frame 2's bottom rows (frame 2 keeps the body).
The portrait grids were drafted with the mondraw shape helper (armour, pauldrons, cape, feathers), heads, helmets,
beards and props stamped by hand, then split into background + sprite layers by mondraw.famicom().
nes_portraits.py and nes_sprites.py merge PORTRAITS, SPRITES and HEIGHTS from here.
"""



def _G(t):
    rows = [ln.strip() for ln in t.strip(chr(10)).split(chr(10))]
    assert len(rows) == 24 and all(len(r) == 16 for r in rows), rows
    return rows


